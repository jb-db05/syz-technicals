# ────────────────────────────────────────────────────────────────────────────────────────────────────────────
# Indicators – moving average  (syztech/indicators/ma.py)
# ────────────────────────────────────────────────────────────────────────────────────────────────────────────
def sma(close: pd.Series, window: int) -> pd.Series:
    """Simple moving average; NaN until `window` bars are available."""
    return close.rolling(window, min_periods=window).mean()


# ────────────────────────────────────────────────────────────────────────────────────────────────────────────
# Indicators – slope of an average  (syztech/indicators/slope.py)
# ────────────────────────────────────────────────────────────────────────────────────────────────────────────
RISING, FALLING, FLAT = "rising", "falling", "flat"

def slope_ratio(ma: pd.Series, lookback: int = 20) -> pd.Series:
    """MA[t] / MA[t - lookback] - 1."""
    return ma / ma.shift(lookback) - 1.0

def classify(ratio: float, flat_band: float) -> str | None:
    """rising if > +flat_band, falling if < -flat_band, else flat. None when not computable."""
    if ratio is None or pd.isna(ratio):
        return None
    if ratio > flat_band:
        return RISING
    if ratio < -flat_band:
        return FALLING
    return FLAT

def slope_state(ma: pd.Series, lookback: int, flat_band: float) -> pd.Series:
    """Slope classification for every bar (object Series of rising/falling/flat/None)."""
    return slope_ratio(ma, lookback).map(lambda r: classify(r, flat_band))


# ────────────────────────────────────────────────────────────────────────────────────────────────────────────
# Indicators – 100-day high / low band  (syztech/indicators/bands.py)
# ────────────────────────────────────────────────────────────────────────────────────────────────────────────
UPPER, LOWER, NONE = "upper", "lower", "none"

def max_prior(close: pd.Series, window: int = 100) -> pd.Series:
    """Highest close of the prior `window` bars, excluding the current bar."""
    return close.shift(1).rolling(window, min_periods=window).max()

def min_prior(close: pd.Series, window: int = 100) -> pd.Series:
    """Lowest close of the prior `window` bars, excluding the current bar."""
    return close.shift(1).rolling(window, min_periods=window).min()

def band_events(close: pd.Series, window: int = 100) -> tuple[pd.Series, pd.Series]:
    """Boolean Series: close above MAX(window) / close below MIN(window). Strict inequalities."""
    upper = (close > max_prior(close, window)).fillna(False)
    lower = (close < min_prior(close, window)).fillna(False)
    return upper.astype(bool), lower.astype(bool)

@dataclass(frozen=True)
class LastBand:
    side: str                 # upper / lower / none
    pos: int | None           # integer trading-day position of the event bar
    level: float | None       # the MAX100 / MIN100 level that was broken

def last_band(close: pd.Series, window: int = 100) -> LastBand:
    """Most recent band event in the available history."""
    upper, lower = band_events(close, window)
    hi = np.flatnonzero(upper.to_numpy())
    lo = np.flatnonzero(lower.to_numpy())
    last_hi = hi[-1] if hi.size else -1
    last_lo = lo[-1] if lo.size else -1
    if last_hi < 0 and last_lo < 0:
        return LastBand(NONE, None, None)
    if last_hi > last_lo:
        return LastBand(UPPER, int(last_hi), float(max_prior(close, window).iloc[last_hi]))
    return LastBand(LOWER, int(last_lo), float(min_prior(close, window).iloc[last_lo]))

def bollinger_bandwidth(close: pd.Series, window: int = 100, k: float = 2.0) -> pd.Series:
    """(UBB - LBB) / ((UBB + LBB) / 2), population standard deviation."""
    mid = close.rolling(window, min_periods=window).mean()
    sd = close.rolling(window, min_periods=window).std(ddof=0)
    upper, lower = mid + k * sd, mid - k * sd
    return (upper - lower) / ((upper + lower) / 2.0)


# ────────────────────────────────────────────────────────────────────────────────────────────────────────────
# Indicators – golden / death crosses  (syztech/indicators/crosses.py)
# ────────────────────────────────────────────────────────────────────────────────────────────────────────────
GOLDEN, DEATH, UNQUALIFIED, NO_CROSS = "golden", "death", "cross_unqualified", "none"

def cross_events(fast: pd.Series, slow: pd.Series) -> pd.Series:
    """+1 on the bar fast closes above slow (was <= on the prior bar), -1 for the reverse, else 0."""
    diff = fast - slow
    prev = diff.shift(1)
    up = (diff > 0) & (prev <= 0)
    down = (diff < 0) & (prev >= 0)
    return up.astype(int) - down.astype(int)

@dataclass(frozen=True)
class Cross:
    kind: str                 # golden / death / cross_unqualified / none
    direction: str | None     # golden / death (raw direction, also for unqualified crosses)
    pos: int | None

def last_cross(fast: pd.Series, slow: pd.Series, slow_slope: pd.Series, lookback: int) -> Cross:
    """Most recent cross within the last `lookback` bars.

    golden: MA50 crossed above MA200 and the 200-day slope was rising on the cross bar.
    death:  MA50 crossed below MA200 and the 200-day slope was falling on the cross bar.
    Any other cross is `cross_unqualified` and does not count.
    """
    ev = cross_events(fast, slow).to_numpy()
    n = len(ev)
    idx = np.flatnonzero(ev[max(0, n - lookback):]) + max(0, n - lookback)
    if idx.size == 0:
        return Cross(NO_CROSS, None, None)
    p = int(idx[-1])
    direction = GOLDEN if ev[p] > 0 else DEATH
    s = slow_slope.iloc[p]
    if (direction == GOLDEN and s == RISING) or (direction == DEATH and s == FALLING):
        return Cross(direction, direction, p)
    return Cross(UNQUALIFIED, direction, p)


# ────────────────────────────────────────────────────────────────────────────────────────────────────────────
# Indicators – relative strength  (syztech/indicators/rs.py)
# ────────────────────────────────────────────────────────────────────────────────────────────────────────────
def relative_strength(close: pd.Series, benchmark: pd.Series) -> pd.Series:
    """close / benchmark x 100 on common dates (no filling)."""
    both = pd.concat([close, benchmark], axis=1, join="inner").dropna()
    return both.iloc[:, 0] / both.iloc[:, 1] * 100.0

OUTPERFORMING, UNDERPERFORMING, MIXED = "outperforming", "underperforming", "mixed"

def rs_trend(ma200_slope20: float) -> str:
    """RS Mom (Syz screen definition, 10 Nov 2026): direction of the 200-day average of relative strength over
    the last 20 trading days. Rising = outperforming (+), falling = underperforming (−), unchanged = mixed."""
    if ma200_slope20 > 0:
        return OUTPERFORMING
    if ma200_slope20 < 0:
        return UNDERPERFORMING
    return MIXED

def rs_summary(close: pd.Series, benchmark: pd.Series, ma_window: int = 200, slope_window: int = 63) -> dict:
    rs = relative_strength(close, benchmark)
    if len(rs) <= max(ma_window + 20, slope_window):
        return {"rs": None, "rs_ma200": None, "rs_slope63": None, "rs_vs_ma200": None, "rs_chg63": None,
                "rs_ma200_slope20": None, "rs_trend": None}
    ma = sma(rs, ma_window)
    chg = rs.iloc[-1] / rs.iloc[-1 - slope_window] - 1.0
    sign = RISING if chg > 0 else FALLING if chg < 0 else FLAT
    vs = "above" if rs.iloc[-1] > ma.iloc[-1] else "below"
    return {
        "rs": float(rs.iloc[-1]),
        "rs_ma200": float(ma.iloc[-1]),
        "rs_slope63": sign,
        "rs_vs_ma200": vs,
        "rs_chg63": float(chg),
        "rs_ma200_slope20": float(ma.iloc[-1] / ma.iloc[-21] - 1),
        "rs_trend": rs_trend(float(ma.iloc[-1] / ma.iloc[-21] - 1)),
    }


# ────────────────────────────────────────────────────────────────────────────────────────────────────────────
# Indicators – breadth  (syztech/indicators/breadth.py)
# ────────────────────────────────────────────────────────────────────────────────────────────────────────────
def breadth_history(closes: dict[str, pd.Series], index: pd.DatetimeIndex, *, window: int = 200, lookback: int = 20,
                    flat_band: float = 0.002) -> pd.DataFrame:
    """Columns: rising (% with the 200-day average rising), above (% closing above it), n (stocks measured)."""
    rising, above = {}, {}
    for t, c in closes.items():
        c = c.dropna()
        ma = sma(c, window)
        r = slope_ratio(ma, lookback)
        ok = r.notna()
        rising[t] = (r > flat_band).where(ok).reindex(index)
        above[t] = (c > ma).where(ok).reindex(index)
    R, A = pd.DataFrame(rising, index=index, dtype=float), pd.DataFrame(above, index=index, dtype=float)
    n = R.notna().sum(axis=1)
    out = pd.DataFrame({"rising": R.sum(axis=1) / n * 100, "above": A.sum(axis=1) / n * 100, "n": n}, index=index)
    return out.where(n > 0)


